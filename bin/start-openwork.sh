#!/usr/bin/env bash
# start-openwork.sh — managed launcher for the OpenWork headless orchestrator (Phase 29).
#
# WHY THIS EXISTS
#   OpenWork (powered by OpenCode) runs headless via `openwork serve`, which spawns
#   opencode + openwork-server and serves a browser UI on http://127.0.0.1:8787.
#   This launcher runs it as a managed, loopback-only host daemon so you can reach
#   the Cowork workspace in a browser, with the stack's start/stop/doctor funnel.
#
#   `openwork` is the prebuilt orchestrator binary (npm i -g openwork-orchestrator,
#   Phase 29). It SELF-MANAGES OpenCode (downloads + caches sidecars on first run)
#   — no separate `opencode` install, no Node-at-runtime ("ships as a compiled
#   binary, Bun not required at runtime").
#
# FUNNEL INTEGRATION
#   `vz-ai-stack.sh start openwork` invokes this with NO args → the no-arg default
#   is `install` (ensure the launchd daemon + health-gate, idempotent) — NOT a
#   foreground exec. The launchd job itself calls `run` (the foreground server).
#   `vz-ai-stack.sh stop openwork` → bin/stop-openwork.sh → this script's `stop`.
#
# SECURITY
#   Bound to 127.0.0.1 ONLY (never --remote-access / 0.0.0.0). Client + host
#   (approval) tokens are read from .env (generated by Phase 29) and passed via
#   the launchd EnvironmentVariables (env, NOT argv → not visible in `ps`); they
#   are NEVER printed to stdout/log. --approval manual (no host auto-approval).
#   The OPENWORK_LITELLM_KEY is injected as an env var so opencode.json's
#   `{env:OPENWORK_LITELLM_KEY}` resolves without the literal key on disk in argv.
#
# Self-contained on purpose (launchd runs with a minimal PATH and no shell
# profile) — it resolves its own binary and does not source the installer libs.
#
# Usage: start-openwork.sh [install|run|uninstall|status|stop|restart]
set -Eeuo pipefail

if (( BASH_VERSINFO[0] < 5 )); then
  for b in /opt/homebrew/bin/bash /usr/local/bin/bash; do
    [[ -x "$b" ]] && exec "$b" "$0" "$@"
  done
  echo "bin/start-openwork.sh: needs bash 5+" >&2; exit 2
fi

AI_STACK="${AI_STACK:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
STATE="$AI_STACK/installer/state"
LOG="$STATE/openwork.launchd.log"
PLIST="$HOME/Library/LaunchAgents/com.ai-stack.openwork.plist"
LABEL="com.ai-stack.openwork"

# Tunables. Loopback bind is intentional (see SECURITY). 8787 = openwork-server default.
PORT="${OPENWORK_PORT:-8787}"
HOST_BIND="127.0.0.1"
WORKDIR="${OPENWORK_WORKDIR:-$HOME/.openwork-stack}"
SIDECAR_DIR="${OPENWORK_SIDECAR_DIR:-$HOME/.openwork-stack/sidecars}"

mkdir -p "$STATE" "$HOME/Library/LaunchAgents" "$WORKDIR" "$SIDECAR_DIR"

# Read a value from the authoritative .env (KEY=VALUE; tolerates surrounding quotes).
# Used at INSTALL time to bake secrets into the plist EnvironmentVariables.
_envval() {
  local k="$1" line
  line="$(grep -E "^${k}=" "$AI_STACK/.env" 2>/dev/null | tail -1)" || true
  [[ -n "$line" ]] || { echo ""; return 0; }
  line="${line#${k}=}"; line="${line%\"}"; line="${line#\"}"; echo "$line"
}

# Resolve the openwork binary without a login shell (launchd has a minimal PATH).
_find_bin() {
  command -v openwork 2>/dev/null && return 0
  local p
  for p in "$HOME/.local/bin/openwork" "/opt/homebrew/bin/openwork" "/usr/local/bin/openwork"; do
    [[ -x "$p" ]] && { echo "$p"; return 0; }
  done
  if command -v npm >/dev/null 2>&1; then
    p="$(npm prefix -g 2>/dev/null)/bin/openwork"; [[ -x "$p" ]] && { echo "$p"; return 0; }
  fi
  echo ""
}
OPENWORK_BIN="$(_find_bin)"

_listening() { lsof -nP -iTCP:"$PORT" -sTCP:LISTEN 2>/dev/null | grep -q LISTEN; }
# `|| true`: lsof exits 1 when nothing matches; guard against tripping set -e.
_pids()      { lsof -nP -tiTCP:"$PORT" -sTCP:LISTEN 2>/dev/null || true; }

# Probe the live endpoint. openwork-server serves HTTP 200 at /health once up.
# Explicit '^200$' grep (NOT the http_ok helper — documented 000-concat bug).
_healthy() {
  curl -s -m 5 -o /dev/null -w '%{http_code}' "http://$HOST_BIND:$PORT/health" 2>/dev/null | grep -q '^200$'
}

_stop() {
  local pids; pids="$(_pids)"
  if [[ -z "$pids" ]]; then echo "openwork: nothing listening on :$PORT"; else
    echo "openwork: stopping pid(s) $pids on :$PORT"
    # shellcheck disable=SC2086
    kill $pids 2>/dev/null || true
    for _ in 1 2 3 4 5; do _listening || break; sleep 1; done
    if _listening; then local fp; fp="$(_pids)"; [[ -n "$fp" ]] && { echo "openwork: force-killing"; kill -9 $fp 2>/dev/null || true; }; fi
  fi
  # Reap the orchestrator's child sidecars scoped to OUR workspace (don't touch a
  # user's personal opencode). The orchestrator names them with this workspace path.
  pkill -f "openwork serve .*--workspace $WORKDIR" 2>/dev/null || true
  return 0   # never let a "nothing to stop" result trip set -e in callers
}

_do_install() {
  [[ -n "$OPENWORK_BIN" ]] || { echo "openwork not found — run: bash $AI_STACK/vz-ai-stack.sh install 29" >&2; exit 1; }
  local litellm_key client_tok host_tok
  litellm_key="$(_envval OPENWORK_LITELLM_KEY)"
  client_tok="$(_envval OPENWORK_CLIENT_TOKEN)"
  host_tok="$(_envval OPENWORK_HOST_TOKEN)"
  cat > "$PLIST" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array>
    <string>/bin/bash</string><string>$AI_STACK/bin/start-openwork.sh</string><string>run</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>EnvironmentVariables</key><dict>
    <key>AI_STACK</key><string>$AI_STACK</string>
    <key>OPENWORK_PORT</key><string>$PORT</string>
    <key>OPENWORK_WORKDIR</key><string>$WORKDIR</string>
    <key>OPENWORK_SIDECAR_DIR</key><string>$SIDECAR_DIR</string>
    <key>OPENWORK_LITELLM_KEY</key><string>$litellm_key</string>
    <key>OPENWORK_CLIENT_TOKEN</key><string>$client_tok</string>
    <key>OPENWORK_HOST_TOKEN</key><string>$host_tok</string>
    <key>PATH</key><string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
  <key>StandardOutPath</key><string>$LOG</string>
  <key>StandardErrorPath</key><string>$LOG</string>
</dict></plist>
PL
  chmod 600 "$PLIST" 2>/dev/null || true   # plist holds secrets in EnvironmentVariables
  : > "$LOG"; chmod 600 "$LOG" 2>/dev/null || true
  # A pre-existing transient instance would hold the port and make RunAtLoad fail.
  _stop
  launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null || launchctl load "$PLIST" 2>/dev/null || true
  echo "openwork launchd job installed ($LABEL, RunAtLoad+KeepAlive, $HOST_BIND:$PORT)"
  # First run downloads OpenCode sidecars — health can take a while. Poll generously.
  for _ in $(seq 1 30); do _healthy && { echo "openwork: healthy on http://$HOST_BIND:$PORT/health"; return 0; }; sleep 2; done
  echo "openwork: not healthy yet (first run downloads OpenCode sidecars) — check $LOG" >&2; return 0
}

case "${1:-install}" in
  install) _do_install; exit 0 ;;
  uninstall)
    launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || launchctl unload "$PLIST" 2>/dev/null || true
    rm -f "$PLIST"; _stop
    echo "openwork launchd job removed"; exit 0 ;;
  status)
    launchctl print "gui/$(id -u)/$LABEL" 2>/dev/null | grep -iE 'state|pid|last exit' | head \
      || echo "launchd job not loaded"
    if _healthy; then echo "endpoint: http://$HOST_BIND:$PORT/health — HEALTHY (200)"; else echo "endpoint: http://$HOST_BIND:$PORT/health — NOT healthy"; fi
    echo "--- recent log ($LOG) ---"; tail -n 12 "$LOG" 2>/dev/null || echo "(no log yet)"; exit 0 ;;
  stop)
    # Real stop for the `stop openwork` funnel: bootout so KeepAlive won't respawn,
    # then free the port. The plist stays on disk; `start openwork` re-bootstraps it.
    launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
    _stop; exit 0 ;;
  restart)
    _stop
    launchctl kickstart -k "gui/$(id -u)/$LABEL" 2>/dev/null \
      || { launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null || launchctl load "$PLIST" 2>/dev/null || true; }
    echo "openwork: restart requested"; exit 0 ;;
  run) : ;;   # fall through and exec the server (launchd entrypoint)
  *) echo "usage: start-openwork.sh [install|run|uninstall|status|stop|restart]" >&2; exit 2 ;;
esac

# --- foreground server (launchd entrypoint) -----------------------------------
[[ -n "$OPENWORK_BIN" ]] || { echo "openwork not found — run: bash $AI_STACK/vz-ai-stack.sh install 29" >&2; exit 1; }
# Tokens are passed via the ENV ONLY (the binary reads OPENWORK_TOKEN +
# OPENWORK_HOST_TOKEN — verified in its strings table), NEVER as CLI flags, so
# they never appear in `ps`. The plist's EnvironmentVariables set OPENWORK_CLIENT_TOKEN;
# the orchestrator's client-token env name is OPENWORK_TOKEN, so map it here.
# Loopback only: NEVER --remote-access (and we never set OPENWORK_REMOTE_ACCESS).
# --approval manual: agentic actions require explicit approval on the host.
export OPENWORK_LITELLM_KEY
export OPENWORK_TOKEN="${OPENWORK_CLIENT_TOKEN:-}"
export OPENWORK_HOST_TOKEN="${OPENWORK_HOST_TOKEN:-}"
exec "$OPENWORK_BIN" serve \
  --workspace "$WORKDIR" \
  --openwork-host "$HOST_BIND" --openwork-port "$PORT" \
  --opencode-host "$HOST_BIND" \
  --sidecar-dir "$SIDECAR_DIR" \
  --approval manual --no-tui
